"""
Grow Controller persistence on an EXISTING PostgreSQL instance.

Use a dedicated Grow Controller database and minimally privileged application role.
This module does not create databases, roles or extensions, and does not access
Home Server / VPS databases. It creates only its own three tables in the
database designated by GROW_POSTGRES_DSN.
"""
from __future__ import annotations

import json
from datetime import datetime, timedelta
from typing import Any

import pandas as pd
import psycopg
from psycopg.rows import dict_row

_RELAY_COLS = ("heater", "circulation_vent", "exhaust_vent", "pump")
_CREATE_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS readings (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ts TEXT NOT NULL,
        air_temperature DOUBLE PRECISION,
        water_temperature DOUBLE PRECISION,
        case_temperature DOUBLE PRECISION,
        humidity DOUBLE PRECISION,
        light_level DOUBLE PRECISION,
        ec DOUBLE PRECISION,
        ph DOUBLE PRECISION,
        circulation_vent INTEGER NOT NULL,
        exhaust_vent INTEGER NOT NULL,
        heater INTEGER NOT NULL,
        pump INTEGER NOT NULL,
        extras_json TEXT
    )""",
    "CREATE INDEX IF NOT EXISTS idx_readings_ts ON readings(ts)",
    """CREATE TABLE IF NOT EXISTS app_control (
        id INTEGER PRIMARY KEY CHECK (id = 1),
        control_mode TEXT NOT NULL DEFAULT 'auto',
        heater INTEGER NOT NULL DEFAULT 0,
        circulation_vent INTEGER NOT NULL DEFAULT 0,
        exhaust_vent INTEGER NOT NULL DEFAULT 0,
        pump INTEGER NOT NULL DEFAULT 0,
        updated_at TEXT NOT NULL DEFAULT ''
    )""",
    """INSERT INTO app_control
       (id, control_mode, heater, circulation_vent, exhaust_vent, pump, updated_at)
       VALUES (1, 'auto', 0, 0, 0, 0, '')
       ON CONFLICT (id) DO NOTHING""",
    """CREATE TABLE IF NOT EXISTS alerts_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ts TEXT NOT NULL,
        severity TEXT NOT NULL,
        message TEXT NOT NULL,
        source TEXT
    )""",
    "CREATE INDEX IF NOT EXISTS idx_alerts_ts ON alerts_log(ts)",
)
_READ_COLUMNS = """ts, air_temperature, water_temperature, case_temperature,
    humidity, light_level, ec, ph, circulation_vent, exhaust_vent, heater,
    pump, extras_json"""
_INSERT_COLUMNS = """ts, air_temperature, water_temperature, case_temperature,
    humidity, light_level, ec, ph, circulation_vent, exhaust_vent, heater,
    pump, extras_json"""
_INSERT_SQL = (f"INSERT INTO readings ({_INSERT_COLUMNS}) VALUES (" +
               ", ".join(["%s"] * 13) + ")")


def _ts_iso(value: Any) -> str:
    if isinstance(value, datetime):
        return value.isoformat(timespec="seconds")
    if hasattr(value, "isoformat"):
        try:
            return value.isoformat(timespec="seconds")
        except TypeError:
            return value.isoformat()
    return str(value)


def _bool_int(value: Any) -> int:
    return int(bool(value))


class PostgresTelemetryStore:
    """Implements the existing TelemetryStore interface without touching SQLite."""

    def __init__(self, dsn: str, retention_days: int = 90) -> None:
        if not dsn or not dsn.strip():
            raise ValueError("GROW_POSTGRES_DSN is missing")
        self.dsn = dsn
        self.retention_days = retention_days
        self._init_db()

    def _connect(self):
        return psycopg.connect(self.dsn, row_factory=dict_row, connect_timeout=5)

    def _init_db(self) -> None:
        # Requires CREATE only inside the dedicated Grow Controller database.
        # Do not grant this application role rights on any other database.
        with self._connect() as conn:
            with conn.cursor() as cur:
                for stmt in _CREATE_STATEMENTS:
                    cur.execute(stmt)

    def ping(self) -> None:
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT 1")
                if cur.fetchone() is None:
                    raise RuntimeError("ping returned no row")

    def _values(self, row: dict[str, Any], extras: dict[str, Any] | None):
        return (
            _ts_iso(row["timestamp"]),
            row.get("air_temperature"),
            row.get("water_temperature"),
            row.get("case_temperature"),
            row.get("humidity"),
            row.get("light_level"),
            row.get("ec"),
            row.get("ph"),
            _bool_int(row.get("circulation_vent")),
            _bool_int(row.get("exhaust_vent")),
            _bool_int(row.get("heater")),
            _bool_int(row.get("pump")),
            json.dumps(extras, default=str) if extras else None,
        )

    def insert_reading(self, row: dict[str, Any], extras: dict[str, Any] | None = None) -> None:
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(_INSERT_SQL, self._values(row, extras))
                if self.retention_days > 0:
                    cutoff = _ts_iso(datetime.now() - timedelta(days=self.retention_days))
                    cur.execute("DELETE FROM readings WHERE ts < %s", (cutoff,))

    def fetch_latest(self) -> dict[str, Any] | None:
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(f"SELECT {_READ_COLUMNS} FROM readings ORDER BY id DESC LIMIT 1")
                d = cur.fetchone()
        if d is None:
            return None
        d = dict(d)
        raw_extras = d.pop("extras_json")
        try:
            extras = json.loads(raw_extras) if raw_extras else {}
        except (json.JSONDecodeError, TypeError):
            extras = {}
        for col in _RELAY_COLS:
            d[col] = bool(d[col])
        d["timestamp"] = _ts_iso(d.pop("ts"))
        d["extras"] = extras
        # Hardware-v2 status values remain in extras_json to preserve old
        # SQLite/PostgreSQL schemas; expose read-only fields to the UI too.
        if isinstance(extras, dict):
            for key in ("light", "lamp_cooling"):
                if isinstance(extras.get(key), bool):
                    d[key] = extras[key]
        return d

    def query_range(self, start: datetime, end: datetime) -> pd.DataFrame:
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    f"SELECT {_READ_COLUMNS} FROM readings WHERE ts >= %s AND ts <= %s ORDER BY ts ASC",
                    (_ts_iso(start), _ts_iso(end)),
                )
                records = cur.fetchall()
        df = pd.DataFrame.from_records(records)
        if df.empty:
            return df.set_index(pd.DatetimeIndex([], name="timestamp"))
        df["ts"] = pd.to_datetime(df["ts"])
        for col in _RELAY_COLS:
            df[col] = df[col].astype(bool)
        df = df.rename(columns={"ts": "timestamp"}).set_index("timestamp")
        return df

    def bulk_load_dataframe(self, df: pd.DataFrame) -> None:
        # The SQLite demo helper wipes readings first. Never do that on the
        # production PostgreSQL database.
        raise RuntimeError("bulk_load_dataframe is disabled for production PostgreSQL")

    def get_control_state(self) -> dict[str, Any]:
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT * FROM app_control WHERE id = 1")
                d = cur.fetchone()
        if d is None:
            return {
                "control_mode": "auto",
                "targets": {**{k: False for k in _RELAY_COLS}, "water_pump": False},
                "updated_at": _ts_iso(datetime.now()),
            }
        mode = (d.get("control_mode") or "auto").lower()
        if mode not in ("auto", "manual"):
            mode = "auto"
        targets = {k: bool(d[k]) for k in _RELAY_COLS}
        return {
            "control_mode": mode,
            "targets": {**targets, "water_pump": targets["pump"]},
            "updated_at": d.get("updated_at") or _ts_iso(datetime.now()),
        }

    def set_control_mode(self, mode: str) -> None:
        m = mode.lower()
        if m not in ("auto", "manual"):
            raise ValueError("control_mode must be auto or manual")
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "UPDATE app_control SET control_mode = %s, updated_at = %s WHERE id = 1",
                    (m, _ts_iso(datetime.now())),
                )

    def set_control_targets_partial(
        self, updates: dict[str, Any], *, switch_to_manual: bool
    ) -> None:
        mapped: dict[str, bool] = {}
        for key, value in updates.items():
            key = "pump" if key == "water_pump" else key
            if key in _RELAY_COLS:
                mapped[key] = bool(value)
        if not mapped:
            return
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "SELECT heater, circulation_vent, exhaust_vent, pump, control_mode "
                    "FROM app_control WHERE id = 1 FOR UPDATE"
                )
                row = cur.fetchone()
                if row is None:
                    return
                vals = {k: int(row[k]) for k in _RELAY_COLS}
                vals.update({k: int(v) for k, v in mapped.items()})
                mode = "manual" if switch_to_manual else (row["control_mode"] or "auto")
                cur.execute(
                    """UPDATE app_control SET control_mode = %s, heater = %s,
                         circulation_vent = %s, exhaust_vent = %s, pump = %s,
                         updated_at = %s WHERE id = 1""",
                    (mode, vals["heater"], vals["circulation_vent"],
                     vals["exhaust_vent"], vals["pump"], _ts_iso(datetime.now())),
                )

    def sync_relay_targets_from_automation(self, snapshot: dict[str, bool]) -> None:
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    """UPDATE app_control SET heater = %s, circulation_vent = %s,
                       exhaust_vent = %s, pump = %s, updated_at = %s
                       WHERE id = 1 AND control_mode = 'auto'""",
                    tuple(_bool_int(snapshot.get(k)) for k in _RELAY_COLS) +
                    (_ts_iso(datetime.now()),),
                )

    def append_alert(self, severity: str, message: str, source: str | None = None) -> None:
        sev = severity.lower()
        if sev not in ("info", "warn", "error"):
            sev = "warn"
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "INSERT INTO alerts_log (ts, severity, message, source) VALUES (%s,%s,%s,%s)",
                    (_ts_iso(datetime.now()), sev, message, source),
                )

    def fetch_alerts_recent(self, limit: int = 50) -> list[dict[str, Any]]:
        lim = max(1, min(200, limit))
        with self._connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "SELECT ts, severity, message, source FROM alerts_log "
                    "ORDER BY id DESC LIMIT %s",
                    (lim,),
                )
                return [dict(r) for r in cur.fetchall()]
