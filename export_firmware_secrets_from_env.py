"""
Schreibt pro Firmware-Sketch eine `device_secrets.h` aus der Projekt-`.env`.

Erwartete Variablen (sensible Werte nur hier, nicht in den .ino committen):
  IOT_WIFI_SSID, IOT_WIFI_PASSWORD, IOT_TELEMETRY_SERVER_HOST
  TELEMETRY_API_PORT, TELEMETRY_API_KEY (gleiche Keys wie für den Python-Server)
  Optional: IOT_USE_HTTPS=1 (VPS + TLS), IOT_TELEMETRY_SERVER_PORT (oft 443),
  IOT_TLS_INSECURE=1 → ESP32 prüft kein Server-Zertifikat (schnell, aber anfällig für MITM)

Usage (im Projektroot, mit aktivierter venv):
  python export_firmware_secrets_from_env.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from env_config import (
    get_telemetry_api_key,
    get_telemetry_api_port,
    load_dotenv_if_present,
)


def _c_string_literal(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n")
    return f'"{escaped}"'


def _env_truthy(key: str, default: bool = False) -> bool:
    raw = os.environ.get(key, "").strip().lower()
    if raw in ("1", "true", "yes", "on"):
        return True
    if raw in ("0", "false", "no", "off"):
        return False
    return default


def main() -> int:
    root = Path(__file__).resolve().parent
    load_dotenv_if_present()

    ssid = os.environ.get("IOT_WIFI_SSID", "").strip()
    password = os.environ.get("IOT_WIFI_PASSWORD", "").strip()
    host = os.environ.get("IOT_TELEMETRY_SERVER_HOST", "").strip()
    api_key = get_telemetry_api_key() or ""

    use_https = _env_truthy("IOT_USE_HTTPS", False)
    tls_insecure = _env_truthy("IOT_TLS_INSECURE", use_https)
    raw_client_port = os.environ.get("IOT_TELEMETRY_SERVER_PORT", "").strip()
    if raw_client_port:
        try:
            client_port = int(raw_client_port)
        except ValueError:
            client_port = 443 if use_https else get_telemetry_api_port()
    elif use_https:
        client_port = 443
    else:
        client_port = get_telemetry_api_port()

    missing = [n for n, v in (("IOT_WIFI_SSID", ssid), ("IOT_TELEMETRY_SERVER_HOST", host)) if not v]
    if missing:
        print(
            "Fehler: in .env fehlen: " + ", ".join(missing),
            file=sys.stderr,
        )
        print(
            "Trage IOT_WIFI_SSID, IOT_WIFI_PASSWORD, IOT_TELEMETRY_SERVER_HOST ein "
            "(und TELEMETRY_API_PORT / TELEMETRY_API_KEY wie für den Server).",
            file=sys.stderr,
        )
        return 1

    key_decl = _c_string_literal(api_key)
    lines = [
        "/* Generated by export_firmware_secrets_from_env.py — do not commit; do not edit by hand. */",
        "#ifndef GROW_CONTROLLER_DEVICE_SECRETS_H",
        "#define GROW_CONTROLLER_DEVICE_SECRETS_H",
        f"const char *WIFI_SSID = {_c_string_literal(ssid)};",
        f"const char *WIFI_PASS = {_c_string_literal(password)};",
        f"const char *SERVER_HOST = {_c_string_literal(host)};",
        f"const uint16_t SERVER_PORT = {client_port};",
        f"const char *TELEMETRY_API_KEY = {key_decl};",
        f"const bool SERVER_USE_HTTPS = {'true' if use_https else 'false'};",
        f"const bool SERVER_TLS_INSECURE = {'true' if tls_insecure else 'false'};",
        "#endif",
        "",
    ]
    body = "\n".join(lines)

    sketch_dirs = [
        root / "firmware" / "growroom_telemetry_client",
        root / "firmware" / "powerbox_actuator",
        root / "firmware" / "cyd_remote_control",
        root / "firmware" / "cyd_grow_display",
    ]
    for d in sketch_dirs:
        if not d.is_dir():
            print(f"Warnung: überspringe fehlendes Verzeichnis {d}", file=sys.stderr)
            continue
        out = d / "device_secrets.h"
        out.write_text(body, encoding="utf-8")
        print(f"OK: {out}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
